"""
Enterprise-CRAG 全局状态定义模块 (LangGraph State Architecture)
==============================================================
核心架构职责与设计哲学：
1. 【全局共享黑板模式 (Blackboard Pattern)】：
   - LangGraph 的所有节点 (Node) 都是无状态纯函数，其入参与返回值均基于强类型状态字典；
   - 每个节点只消费自己需要的字段，并在返回时产出增量字典，由 LangGraph 自动合并 (Reducer)；
2. 【全生命周期信息流追溯】：
   - 涵盖从用户输入、多轮会话窗口、混合检索命中的子块、逆向展开的父块、
     Corrective 评分信号、联网搜索补偿、LLM 生成回答、反思质检结果到审计轨迹的全部字段；
3. 【强类型约束 (TypedDict)】：
   - 避免使用非结构化字典带来的拼写错误与键名丢失，为 IDE 提供精准的代码补全与静态检查。
"""

from typing import List, Dict, Any, TypedDict, Optional


class GraphState(TypedDict):
    """
    CRAG 状态图全局流转状态树 (Global Execution State)
    -------------------------------------------------
    贯穿整个问答流程的所有节点与条件边。
    """

    # =========================================================================
    # 1. 用户输入与对话上下文 (Input & Dialogue Context)
    # =========================================================================
    # 用户本轮输入的原始自然语言问题 (例如: "公司的年假天数是如何规定的？")
    question: str

    # 客户端或 API 分配的会话唯一标识 UUID，用于多会话隔离与关系库数据落地
    session_id: str

    # 格式化拼接的多轮历史对话上下文 (通常为滑动窗口前 3~5 轮 "用户: ...\n助手: ...")
    chat_history: str

    # 业务限定检索的知识库主文档 ID 列表 (例如 [1, 3])；若为 None 则默认在全库范围内检索
    filter_doc_ids: Optional[List[int]]

    # =========================================================================
    # 2. 检索召回与父子拓扑回溯 (Retrieval & Parent-Child Expansion)
    # =========================================================================

    # 通过命中子块的 parent_id 逆向精准反查展开的完整父文档块拼接语境 (~1500字/块)
    # 作为核心证据输入提供给大模型生成节点，保证段落逻辑不被割裂
    parent_context: str

    # 结构化引用溯源详情列表，每项包含:
    # {"filename": "xxx.pdf", "parent_id": "doc_1_p0", "child_id": "doc_1_c0_0", "preview": "..."}
    # 供 Streamlit 界面和 RESTful 响应体渲染前端引用来源抽屉
    sources: List[Dict[str, Any]]

    # =========================================================================
    # 3. 自校正 (Corrective RAG) 评估与外部补偿
    # =========================================================================
    # 知识充分性开关：由 grade_documents_node 判定。
    # 若为 True，代表本地知识库未召回相关内容或信息不足，条件边将引导至 web_search 节点
    web_search_required: bool

    # 外部搜索引擎 (DuckDuckGo) 获取的实时公网补充知识文本
    web_context: str

    # 评估专家节点给出的相关度判定理由 (一句话评语，用于日志追踪与可解释性)
    grade_reasoning: str

    # =========================================================================
    # 4. 回答生成与事实一致性反思闭环 (Generation & Self-Reflection)
    # =========================================================================
    # 主力问答大模型当前轮次生成的回答草稿或最终答案文本
    generation: str

    # 自纠错重试计数器 (从 0 开始自增)。当触发幻觉核查不通过时 +1；
    # 当 retry_count >= MAX_RETRIES (默认3次) 时，条件边强制终止以防死循环
    retry_count: int

    # 幻觉检测结论：由 hallucination_check_node 质检判定。
    # True 代表回答中包含了参考资料未提及的无中生有/虚构信息
    hallucination_detected: bool

    # 事实质检员节点给出的核查评语与判定理由
    hallucination_reasoning: str

    # =========================================================================
    # 5. 可视化审计与流转轨迹 (Observability & Audit Trail)
    # =========================================================================
    # 记录状态机实际依次走过的节点名称序列，例如:
    # ["retrieve", "grade_documents", "web_search", "generate", "hallucination_check"]
    # 供终端和前端界面渲染彩色的“CRAG 执行状态流转指示灯”
    execution_steps: List[str]
