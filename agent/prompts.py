"""
Enterprise-CRAG 提示词模板中心 (Centralized Prompt Engineering Center)
========================================================================
架构职责与提示工程规范：
1. 【集中化管理】：杜绝硬编码分散在各业务代码中，统一集中在此模块进行版本迭代与调优；
2. 【严格的角色与目标定义】：System Message 明确赋予模型特定的专业职责（评估官、问答助手、核查质检员）；
3. 【清晰的边界与负向约束 (Negative Constraints)】：
   - GRADE_PROMPT         : 严谨评定召回文档是否包含核心依据，驱动 Corrective 状态分支；
   - GENERATE_PROMPT      : 严格基于上下文（事实优先、诚实严谨、不胡乱推测），杜绝编造；
   - HALLUCINATION_PROMPT : 独立作为第三方事实一致性质检员，检验生成内容与上下文的一致性；
   - NORMAL_CHAT_PROMPT   : 通用闲聊与兜底对话模板。
"""

from langchain_core.prompts import ChatPromptTemplate, PromptTemplate


# =============================================================================
# 1. 文档相关性评分 Prompt (用于 Corrective 路由判断)
# =============================================================================
# 提示工程设计原理：
# - 任务目标：二元分类任务 (is_relevant: bool) + 极简判定理由；
# - 判定宽松度：只要包含相关事实或流程即算相关（召回倾向），避免误杀相关文档导致频繁调外部搜索；
# - 输入槽位：{question} 用户问题, {context} 展开的父文档语境。
GRADE_PROMPT = ChatPromptTemplate.from_messages([
    (
        "system",
        """你是一名严谨的企业知识库评估专家。
请仔细评估提供的【参考资料】中是否包含能够回答【用户问题】的核心事实或关键信息。
评估准则：
1. 只要资料中包含有助于回答问题的直接依据、相关定义、操作流程或背景事实，即判定为相关 (is_relevant=True)；
2. 如果资料内容与问题完全无关、或者即使参考该资料也无法对问题产生任何帮助，则判定为不相关 (is_relevant=False)；
3. 请客观、严格，不要随意猜测。给出极简明扼要的一句话判定理由。"""
    ),
    (
        "human",
        """【用户问题】: {question}

【参考资料】:
{context}

请给出你的评估结果。"""
    )
])


# =============================================================================
# 2. 知识库回答生成 Prompt (LCEL 链式管道核心)
# =============================================================================
# 提示工程设计原理：
# - 任务目标：高质量生成结构化、易读、诚实、有理有据的企业级回答；
# - 引用优先级：本地参考资料 > 联网补充资料；
# - 防幻觉强制准则：“若资料中没有，明确回答未找到”，严禁胡乱猜测；
# - 输入槽位：{chat_history} 滑动窗口记忆, {parent_context} 逆向展开父块, {web_context} 外部搜索补偿, {question} 当前问题。
GENERATE_PROMPT = ChatPromptTemplate.from_messages([
    (
        "system",
        """你是一名专业、可靠的企业智能知识问答助手。请严格基于以下给出的【本地参考资料】与【联网补充资料】回答用户的问题。

回答准则：
1. 【事实优先】：所有关键论述必须有依据，优先采纳本地参考资料；如果触发了联网补充资料，可结合补充。
2. 【诚实严谨】：若上下文资料中没有相关信息，请明确诚实地回答“根据现有企业知识库及补充资料，未能找到相关信息”，严禁胡乱编造。
3. 【逻辑清晰】：采用结构化分点排版，突出核心结论与重要细节。
4. 【多轮对话】：结合提供的历史对话背景，理解用户的代词与上下文关联。"""
    ),
    (
        "human",
        """【历史对话】:
{chat_history}

【本地参考资料】:
{parent_context}

【联网补充资料】:
{web_context}

【当前问题】: {question}

请给出详尽、准确、有条理的回答："""
    )
])


# =============================================================================
# 3. 事实一致性与幻觉反思 Prompt (Self-Reflection Loop)
# =============================================================================
# 提示工程设计原理：
# - 任务目标：大模型事实一致性对齐检验 (Fact Consistency / Hallucination Detection)；
# - 核心逻辑：生成的回答中，是否存在【参考资料】完全未支持的陈述？
# - 特别边界处理：若模型礼貌告知“资料中未提及相关信息”，这属于合规诚实的回答，严格判定为无幻觉 (has_hallucination=False)！
# - 输入槽位：{context} 全部参考资料 (本地+联网), {generation} 生成的回答草稿。
HALLUCINATION_PROMPT = ChatPromptTemplate.from_messages([
    (
        "system",
        """你是一名严格的大模型事实核查质检员。
你的任务是核查【生成的回答】中是否存在【参考资料】中完全没有支持的虚构、捏造或自相矛盾的事实（即大模型幻觉）。

核查准则：
1. 如果回答中的核心事实、数据、专有名词均能在参考资料中找到依据，判定为无幻觉 (has_hallucination=False)；
2. 如果回答中包含参考资料未曾提及的具体规则、虚构数据、无中生有的人名或政策，判定为存在幻觉 (has_hallucination=True)；
3. 如果模型在参考资料不足时礼貌告知“资料中未提及相关信息”，这属于合规诚实的回答，不是幻觉 (has_hallucination=False)；
4. 给出简练的一句话核查理由。"""
    ),
    (
        "human",
        """【全部参考资料】:
{context}

【生成的回答】:
{generation}

请完成核查判定："""
    )
])


